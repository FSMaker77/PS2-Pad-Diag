#!/usr/bin/env python3
"""Generate the 6x8 bitmap font + merged rectangle list for the PS2 tester.

Source: Terminus (SIL Open Font License 1.1), taken from the Linux console
font Lat15-Terminus12x6.psf.gz.  The 12-row PSF cell is cropped to the 8 rows
and 6 columns actually used by the glyph artwork.
"""
import gzip

PSF = "/usr/share/consolefonts/Lat15-Terminus12x6.psf.gz"
W, H = 5, 10


def load():
    d = gzip.open(PSF, "rb").read()
    out = {}
    for code in range(32, 127):
        base = 32 + code * 12
        rows = []
        for y in range(2, 12):
            b = d[base + y]
            bits = 0
            for x in range(W):
                if (b >> (7 - x)) & 1:
                    bits |= 1 << x
            rows.append(bits)
        out[chr(code)] = rows
    return out


def rects(rows):
    """Merge equal horizontal runs on consecutive rows into rectangles."""
    active = {}   # (x0, x1) -> rect index
    out = []
    for y in range(H):
        runs = []
        x = 0
        while x < W:
            if (rows[y] >> x) & 1:
                x0 = x
                while x < W and (rows[y] >> x) & 1:
                    x += 1
                runs.append((x0, x - 1))
            else:
                x += 1
        new = {}
        for r in runs:
            if r in active:
                i = active[r]
                out[i][3] += 1
                new[r] = i
            else:
                new[r] = len(out)
                out.append([r[0], y, r[1] - r[0] + 1, 1])
        active = new
    return out


font = load()


def rects(rows):
    """Merge equal horizontal runs on consecutive rows into rectangles."""
    active = {}
    out = []
    for y in range(H):
        runs = []
        x = 0
        while x < W:
            if (rows[y] >> x) & 1:
                x0 = x
                while x < W and (rows[y] >> x) & 1:
                    x += 1
                runs.append((x0, x - 1))
            else:
                x += 1
        new = {}
        for r in runs:
            if r in active:
                i = active[r]
                out[i][3] += 1
                new[r] = i
            else:
                new[r] = len(out)
                out.append([r[0], y, r[1] - r[0] + 1, 1])
        active = new
    return out


chars = sorted(font, key=ord)
allrects, offs, cnts = [], [], []
for ch in chars:
    r = rects(font[ch])
    offs.append(len(allrects))
    cnts.append(len(r))
    allrects += r

print("/* Generated by tools/genfont.py -- do not edit by hand. */")
print("/* Font: Terminus, SIL Open Font License 1.1. */")
print("#ifndef FONT6X8_H")
print("#define FONT6X8_H")
print("")
print("#include <stdint.h>")
print("")
print("#define FONT_W 5")
print("#define FONT_H 10")
print("#define FONT_ADV 6")
print("")
print("/* Glyph rectangles: x, y, w, h inside a FONT_W x FONT_H cell. */")
print("static const uint8_t font_rects[][4] = {")
for r in allrects:
    print("\t{ %d, %d, %d, %d }," % tuple(r))
print("};")
print("")
print("static const uint16_t font_rect_off[95] = {")
for i in range(0, 95, 10):
    print("\t" + ", ".join("%d" % v for v in offs[i:i+10]) + ("," if i+10 < 95 else ""))
print("};")
print("")
print("static const uint8_t font_rect_cnt[95] = {")
for i in range(0, 95, 10):
    print("\t" + ", ".join("%d" % v for v in cnts[i:i+10]) + ("," if i+10 < 95 else ""))
print("};")
print("")
print("#endif /* FONT6X8_H */")
